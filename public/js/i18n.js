let current = "en";

export function detectLang() {
  const nav = typeof navigator !== "undefined" && navigator.language ? navigator.language : "";
  return String(nav).toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function setLang(lang) {
  current = lang === "tr" ? "tr" : "en";
  return current;
}

export function getLang() {
  return current;
}

export function t(key, params) {
  const dict = current === "tr" ? TR : EN;
  let text = dict[key] ?? EN[key] ?? key;
  if (params) {
    for (const name of Object.keys(params)) {
      text = text.split(`{${name}}`).join(String(params[name] ?? ""));
    }
  }
  return text;
}

/** Swap only untouched defaults (Player 1 \u2194 Oyuncu 1). Custom names stay. */
export function localizeName(name, index, lang) {
  const slot = index === 1 ? 1 : 0;
  const langKey = lang === "tr" ? "tr" : "en";
  const trimmed = String(name ?? "").trim();
  if (trimmed === NAME_DEFAULTS.en[slot] || trimmed === NAME_DEFAULTS.tr[slot]) {
    return NAME_DEFAULTS[langKey][slot];
  }
  return name;
}

export function positionLabel(position) {
  const raw = String(position ?? "");
  if (current !== "tr") return raw;
  const key = raw.trim().toLowerCase();
  return POS_TR[key] || raw;
}

export function translatePitchRole(role) {
  const raw = String(role ?? "");
  if (current !== "tr") return raw;
  return PITCH_TR[raw] || raw;
}
